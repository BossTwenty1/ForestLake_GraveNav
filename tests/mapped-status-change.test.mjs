import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { createTestDatabase } from "./database-helper.mjs";
import { gisLogin, seedGisFixtures } from "./gis-fixtures.mjs";

test("mapped status changes preserve coordinates and protect plots with burials", async t => {
  const db = await createTestDatabase({ throughMigration: "20261127090000_staff_change_mapped_status.sql" });
  t.after(() => db.close());
  await seedGisFixtures(db);
  await db.exec("update public.area set boundary_geom=extensions.st_geomfromtext('POLYGON((123.7 13.1,123.8 13.1,123.8 13.2,123.7 13.2,123.7 13.1))',4326)::extensions.geography where area_id=1");
  await gisLogin(db);
  const save = async (entity,values) => (await db.query("select public.staff_save_record($1,null,null,$2::jsonb,$3,'save') value",[entity,JSON.stringify(values),randomUUID()])).rows[0].value;
  const plot = await save("lot",{ area_id:1,lot_code:"TEST-STATUS",status:"AVAILABLE",grave_type:"regular",grave_policy_reference:"Fictional test",location_geom:{type:"Point",coordinates:[123.74,13.12]} });
  await db.exec("reset role");
  const selection = await readFile(new URL("../scripts/phase2-staging/install-capstone-visitor-selection.sql", import.meta.url),"utf8");
  await db.exec(selection.split("-- Keep normal operational eligibility")[0]+"commit;");
  await db.exec(await readFile(new URL("../scripts/phase2-staging/install-capstone-planning-assignments.sql", import.meta.url),"utf8"));
  const hash="02a4dba490872f9be8cf56280ccf432d31796431c1f808f542fbff86ac28ca77";
  await db.query("insert into gis_private.capstone_planning_lot(lot_id,plan_sha256,cad_candidate_id,review_reference) values ($1,$2,'lawn:99991','Fictional test')",[plot.id,hash]);
  await gisLogin(db);
  const change = (status,revision) => db.query("select public.staff_change_mapped_status('lawn:99991',$1,$2,'TEST-STATUS',$3,$4,$5)",[hash,plot.id,revision,status,randomUUID()]);
  await change("booked",plot.revision);
  await assert.rejects(change("available",plot.revision),/changed this record/i);
  let state=(await db.query("select revision,status,hold_kind from public.lot where lot_id=$1",[plot.id])).rows[0];
  assert.equal(state.status,"BOOKED");
  await change("unavailable",state.revision);
  state=(await db.query("select revision,status,hold_kind from public.lot where lot_id=$1",[plot.id])).rows[0];
  assert.equal(state.status,"HOLD"); assert.equal(state.hold_kind,"unavailable");
  await change("available",state.revision);
  state=(await db.query("select revision,status,hold_kind from public.lot where lot_id=$1",[plot.id])).rows[0];
  assert.equal(state.status,"AVAILABLE"); assert.equal(state.hold_kind,null);
  await save("burial_record",{lot_id:Number(plot.id),display_name:"Fictional",record_status:"pending",public_display:false,interment_status:"PERMANENT",remains_type:"ASH"});
  await assert.rejects(change("booked",state.revision),/has burial records/i);
  await db.exec("reset role");
  const coords=(await db.query("select extensions.st_x(location_geom::extensions.geometry) x,extensions.st_y(location_geom::extensions.geometry) y from public.lot where lot_id=$1",[plot.id])).rows[0];
  assert.equal(coords.x,123.74); assert.equal(coords.y,13.12);
});
