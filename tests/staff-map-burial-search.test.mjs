import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { createTestDatabase } from "./database-helper.mjs";
import { gisActors, gisLogin, seedGisFixtures } from "./gis-fixtures.mjs";

test("staff map search protects private records and returns only existing plot links", async t => {
  const db = await createTestDatabase({ throughMigration: "20261127120000_staff_map_burial_search.sql" });
  t.after(() => db.close());
  await seedGisFixtures(db);
  await gisLogin(db);
  const save = async (entity, values) => (await db.query("select public.staff_save_record($1,null,null,$2::jsonb,$3,'save') result", [entity, JSON.stringify(values), randomUUID()])).rows[0].result;
  const lot = await save("lot", { area_id: 1, lot_code: "P2S-" + "a".repeat(64), status: "AVAILABLE", grave_type: "regular", grave_policy_reference: "Fictional test" });
  const record = await save("burial_record", { lot_id: Number(lot.id), display_name: "Fictional private person", public_display: false, record_status: "pending", interment_status: "PERMANENT", remains_type: "ASH" });
  const namedLot = await save("lot", { area_id: 1, lot_code: "TEST-ROW-42-3", status: "AVAILABLE", grave_type: "regular", grave_policy_reference: "Fictional test" });
  const secondRecord = await save("burial_record", { lot_id: Number(namedLot.id), display_name: "Fictional other person", public_display: false, record_status: "pending", interment_status: "PERMANENT", remains_type: "ASH" });
  const hash = "02a4dba490872f9be8cf56280ccf432d31796431c1f808f542fbff86ac28ca77";
  const search = async query => (await db.query("select public.staff_map_burial_search($1,$2) result", [query, hash])).rows[0].result;
  await gisLogin(db, null, "anon");
  await assert.rejects(search("fictional"), /permission denied/i);
  await gisLogin(db, gisActors.inactive);
  await assert.rejects(search("fictional"), /staff access/i);
  await gisLogin(db, gisActors.manager);
  await assert.rejects(search("x"), /at least two/i);
  let result = await search("PRIVATE PERSON");
  assert.deepEqual(result.items, [{ id: String(record.id), name: "Fictional private person", candidate: null, plotCode: null }]);
  assert.equal((await search("row-42")).items[0].id, String(secondRecord.id));
  assert.deepEqual((await search("row-42")).plots.items, [{ id: String(namedLot.id), code: "TEST-ROW-42-3", candidate: null }]);
  assert.equal((await search("P2S-")).items.length, 0);
  assert.equal((await search("P2S-")).plots.items.length, 0);
  await db.exec("reset role");
  const selection = await readFile(new URL("../scripts/phase2-staging/install-capstone-visitor-selection.sql", import.meta.url), "utf8");
  await db.exec(selection.split("-- Keep normal operational eligibility")[0] + "commit;");
  await db.exec(await readFile(new URL("../scripts/phase2-staging/install-capstone-planning-assignments.sql", import.meta.url), "utf8"));
  await db.query("insert into gis_private.capstone_planning_lot(lot_id,plan_sha256,cad_candidate_id,review_reference) values ($1,$2,'lawn:99991','Fictional test')", [lot.id, hash]);
  await gisLogin(db, gisActors.manager);
  result = await search("private person");
  assert.equal(result.items[0].candidate, "lawn:99991");
  assert.equal(result.items[0].plotCode, null);
  assert.equal(result.more, false);
  await db.exec("reset role; create schema phase2_review; create table phase2_review.plot_draft (proposed_code text, cad_candidate text); insert into phase2_review.plot_draft values ('MPG-D-183-5','lawn:79')");
  await gisLogin(db, gisActors.manager);
  const proposed = await search("mpg-d-183-5");
  assert.deepEqual(proposed.draftPlots.items, [{ code: "MPG-D-183-5", candidate: "lawn:79" }]);
  assert.equal(proposed.plots.items.length, 0);
  await gisLogin(db, null, "anon");
  await assert.rejects(search("MPG-D-183-5"), /permission denied/i);
});
