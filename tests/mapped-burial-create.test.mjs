import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { createTestDatabase } from "./database-helper.mjs";
import { gisLogin, seedGisFixtures } from "./gis-fixtures.mjs";

test("map burial creation validates the linked plot and preserves capacity and privacy", async t => {
  const db = await createTestDatabase({ throughMigration: "20261127060000_staff_create_mapped_burial.sql" });
  t.after(() => db.close());
  await seedGisFixtures(db);
  await db.exec("update public.area set boundary_geom=extensions.st_geomfromtext('POLYGON((123.7 13.1,123.8 13.1,123.8 13.2,123.7 13.2,123.7 13.1))',4326)::extensions.geography where area_id=1");
  await gisLogin(db);
  const lot = (await db.query("select public.staff_save_record('lot',null,null,$1::jsonb,$2,'save') result", [JSON.stringify({ area_id: 1, lot_code: "MAP-TEST-1", status: "AVAILABLE", grave_type: "regular", grave_policy_reference: "Fictional test", location_geom: {type:"Point",coordinates:[123.74,13.12]} }), randomUUID()])).rows[0].result;
  await db.exec("reset role");
  const selection = await readFile(new URL("../scripts/phase2-staging/install-capstone-visitor-selection.sql", import.meta.url), "utf8");
  await db.exec(selection.split("-- Keep normal operational eligibility")[0] + "commit;");
  await db.exec(await readFile(new URL("../scripts/phase2-staging/install-capstone-planning-assignments.sql", import.meta.url), "utf8"));
  const hash = "02a4dba490872f9be8cf56280ccf432d31796431c1f808f542fbff86ac28ca77";
  await db.query("insert into gis_private.capstone_planning_lot(lot_id,plan_sha256,cad_candidate_id,review_reference) values ($1,$2,'lawn:99991','Fictional test')", [lot.id,hash]);
  const payload = { display_name:"Fictional person", sex:"female", birth_date:"1950-01-01", death_date:"2020-01-01", interment_status:"PERMANENT", remains_type:"ASH" };
  const create = (values=payload, code="MAP-TEST-1", request=randomUUID(), id=lot.id) => db.query("select public.staff_create_mapped_burial('lawn:99991',$1,$2,$3,$4::jsonb,$5) result", [hash,id,code,JSON.stringify(values),request]);
  await gisLogin(db,null,"anon");
  await assert.rejects(create(), /permission denied|staff access/i);
  await gisLogin(db);
  await assert.rejects(create(payload,"WRONG-CODE"), /not ready/i);
  await assert.rejects(create(payload,"MAP-TEST-1",randomUUID(),99999), /link changed/i);
  await assert.rejects(create({...payload,birth_date:"2021-01-01"}), /dates/i);
  await assert.rejects(create({...payload,sex:""}), /required/i);
  const request = randomUUID();
  const withOwner = {...payload,owner:{mode:"new",first_name:"Fictional",last_name:"Owner",address:"Test address",middle_name:"M",representative_name:"Test representative"}};
  const first = (await create(withOwner,"MAP-TEST-1",request)).rows[0].result;
  assert.equal((await create(withOwner,"MAP-TEST-1",request)).rows[0].result.id, first.id);
  await assert.rejects(create(payload,"MAP-TEST-1",request), /reused/i);
  await db.exec("reset role");
  const plot = (await db.query("select lot_owner_id, extensions.st_x(location_geom::extensions.geometry) longitude, extensions.st_y(location_geom::extensions.geometry) latitude from public.lot where lot_id=$1", [lot.id])).rows[0];
  assert.ok(plot.lot_owner_id);
  assert.equal(plot.longitude,123.74);
  assert.equal(plot.latitude,13.12);
  const storedOwner = (await db.query("select first_name,middle_name,last_name,representative_name from public.lot_owner where lot_owner_id=$1", [plot.lot_owner_id])).rows[0];
  assert.equal(storedOwner.middle_name,"M");
  assert.equal(storedOwner.representative_name,"Test representative");
  await gisLogin(db);
  const status = (await db.query("select public.staff_planning_plot_statuses($1) value", [hash])).rows[0].value;
  assert.ok(status.occupied.includes("lawn:99991"));
  await assert.rejects(create({...payload,owner:{mode:"new",first_name:"Other",last_name:"Owner",address:"Elsewhere"}}), /already has a different owner/i);
  await create({...payload,display_name:"Fictional 2",owner:{mode:"existing",id:String(plot.lot_owner_id)}});
  for (let i=3;i<=6;i++) await create({...payload,display_name:`Fictional ${i}`});
  await assert.rejects(create({...payload,display_name:"Seventh"}), /capacity/i);
  const mausoleum=(await db.query("select public.staff_save_record('lot',null,null,$1::jsonb,$2,'save') result",[JSON.stringify({area_id:1,lot_code:"MPC-C-1-12",status:"AVAILABLE",grave_type:"mausoleum",grave_policy_reference:"Fictional test"}),randomUUID()])).rows[0].result;
  await db.exec("reset role");
  await db.query("insert into gis_private.capstone_planning_lot(lot_id,plan_sha256,cad_candidate_id,review_reference) values ($1,$2,'estates:99991','Fictional whole mausoleum')",[mausoleum.id,hash]);
  await gisLogin(db);
  for(let i=1;i<=7;i++) await db.query("select public.staff_create_mapped_burial('estates:99991',$1,$2,'MPC-C-1-12',$3::jsonb,$4)",[hash,mausoleum.id,JSON.stringify({...payload,display_name:`Mausoleum fictional ${i}`}),randomUUID()]);
  const count=(await db.query("select count(*)::int n from public.burial_record where lot_id=$1",[mausoleum.id])).rows[0].n;
  assert.equal(count,7,"a mausoleum accepts more than six burials");
  await gisLogin(db,null,"anon");
  assert.equal((await db.query("select count(*)::int n from public.public_burial_records where burial_id=$1", [first.id])).rows[0].n, 0);
});
