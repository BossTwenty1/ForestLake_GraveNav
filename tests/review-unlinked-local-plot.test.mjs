import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { test } from "node:test";
import { createTestDatabase } from "./database-helper.mjs";
import { gisActors, gisLogin, seedGisFixtures } from "./gis-fixtures.mjs";

test("a reviewed local plot stays unavailable until staff changes its status", async t => {
  const db = await createTestDatabase({ throughMigration: "20261127120000_staff_map_burial_search.sql" });
  t.after(() => db.close());
  await seedGisFixtures(db);
  await db.exec("update public.area set boundary_geom=extensions.st_geomfromtext('POLYGON((123.7 13.1,123.8 13.1,123.8 13.2,123.7 13.2,123.7 13.1))',4326)::extensions.geography where area_id=1");
  await gisLogin(db);
  const lot = (await db.query("select public.staff_save_record('lot',null,null,$1::jsonb,$2,'save') result", [JSON.stringify({ area_id: 1, lot_code: "OLD-LOCAL-1", status: "HOLD", location_geom: {type:"Point",coordinates:[123.74,13.12]} }), randomUUID()])).rows[0].result;
  await db.exec("reset role");
  const selection = await readFile(new URL("../scripts/phase2-staging/install-capstone-visitor-selection.sql", import.meta.url), "utf8");
  await db.exec(selection.split("-- Keep normal operational eligibility")[0] + "commit;");
  await db.exec(await readFile(new URL("../scripts/phase2-staging/install-capstone-planning-assignments.sql", import.meta.url), "utf8"));
  await db.exec("create schema phase2_review; create table phase2_review.plot_draft(cad_candidate text,proposed_code text,lot_type text,review_availability text,review_status text); create table phase2_review.prior_plot_candidates(cad_candidate text,old_lot_id bigint,export_distance_m numeric)");
  await db.exec("insert into phase2_review.plot_draft values('lawn:99991','MPG-D-183-1','Premium','temporarily_unavailable','Review required')");
  await db.query("insert into phase2_review.prior_plot_candidates values('lawn:99991',$1,0.05)",[lot.id]);
  await db.exec(await readFile(new URL("../supabase/migrations/20261127130000_review_unlinked_local_plot.sql",import.meta.url),"utf8"));
  const hash = "02a4dba490872f9be8cf56280ccf432d31796431c1f808f542fbff86ac28ca77";
  const confirm = (revision=lot.revision, note="Compared the fictional CAD and PDF") => db.query("select public.staff_confirm_proposed_plot('lawn:99991',$1,$2,'OLD-LOCAL-1',$3,'MPG-D-183-1',$4,$5)",[hash,lot.id,revision,note,randomUUID()]);
  await gisLogin(db,null,"anon"); await assert.rejects(confirm(),/permission denied/i);
  await gisLogin(db,gisActors.manager); await assert.rejects(confirm(),/administrator/i);
  await gisLogin(db); await assert.rejects(confirm(lot.revision,"short"),/review note/i);
  await assert.rejects(confirm(lot.revision+1),/changed/i);
  await confirm();
  await db.exec("reset role");
  const saved=(await db.query("select lot_code,lot_type,status,hold_kind,coordinate_status,extensions.st_x(location_geom::extensions.geometry) lon,extensions.st_y(location_geom::extensions.geometry) lat from public.lot where lot_id=$1",[lot.id])).rows[0];
  assert.deepEqual(saved,{lot_code:"MPG-D-183-1",lot_type:"premium",status:"HOLD",hold_kind:"unavailable",coordinate_status:"pending",lon:123.74,lat:13.12});
  assert.equal((await db.query("select count(*)::int n from public.burial_record where lot_id=$1",[lot.id])).rows[0].n,0);
  await gisLogin(db);
  await assert.rejects(confirm(),/changed/i);
  const link=(await db.query("select public.staff_proposed_plot_review('lawn:99991',$1) value",[hash])).rows[0].value;
  assert.equal(link,null);
  let revision=(await db.query("select revision from public.lot where lot_id=$1",[lot.id])).rows[0].revision;
  await db.query("select public.staff_review_mapped_coordinates('lawn:99991',$1,$2,'MPG-D-183-1',$3,'verified','',$4)",[hash,lot.id,revision,randomUUID()]);
  revision=(await db.query("select revision from public.lot where lot_id=$1",[lot.id])).rows[0].revision;
  await db.query("select public.staff_change_mapped_status('lawn:99991',$1,$2,'MPG-D-183-1',$3,'available',$4)",[hash,lot.id,revision,randomUUID()]);
  const final=(await db.query("select status,coordinate_status from public.lot where lot_id=$1",[lot.id])).rows[0];
  assert.deepEqual(final,{status:"AVAILABLE",coordinate_status:"verified"});
});
