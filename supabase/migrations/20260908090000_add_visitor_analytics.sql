-- Anonymous visitor analytics for GraveNav.
--
-- These tables are deliberately separate from account, audit_log, and the
-- operational cemetery tables. Visitors do not need Auth accounts. The
-- application creates a random session UUID and submits events through the
-- protected RPCs below; raw tables are not exposed to visitors.

create table public.visitor_session (
    session_id uuid primary key,
    started_at timestamptz not null default current_timestamp,
    ended_at timestamptz,
    last_seen_at timestamptz not null default current_timestamp,
    device_type text not null default 'unknown',
    constraint visitor_session_device_type_check
        check (device_type in ('desktop', 'mobile', 'tablet', 'unknown')),
    constraint visitor_session_time_order_check
        check (ended_at is null or ended_at >= started_at)
);

comment on table public.visitor_session is
    'Anonymous analytics sessions; session_id is not an Auth account identifier.';

create table public.visitor_event (
    event_id bigint generated by default as identity primary key,
    session_id uuid not null references public.visitor_session(session_id) on delete cascade,
    event_name text not null,
    event_timestamp timestamptz not null default current_timestamp,
    properties jsonb not null default '{}'::jsonb,
    constraint visitor_event_properties_object_check
        check (jsonb_typeof(properties) = 'object'),
    constraint visitor_event_properties_size_check
        check (pg_column_size(properties) <= 4096),
    constraint visitor_event_name_check
        check (event_name in (
            'page_viewed',
            'visitor_search_submitted',
            'public_record_opened',
            'map_opened',
            'garden_selected',
            'plot_selected',
            'navigation_started',
            'navigation_completed',
            'navigation_failed',
            'location_permission_denied',
            'gps_accuracy_low'
        ))
);

comment on table public.visitor_event is
    'Validated anonymous visitor events; properties must not contain personal data or raw GPS trails.';

create table public.visitor_navigation (
    navigation_id bigint generated by default as identity primary key,
    session_id uuid not null references public.visitor_session(session_id) on delete cascade,
    started_at timestamptz not null default current_timestamp,
    completed_at timestamptz,
    planned_distance_meters numeric(10, 2),
    estimated_distance_meters numeric(10, 2),
    duration_seconds integer,
    status text not null default 'started',
    error_type text,
    destination_area_code text,
    constraint visitor_navigation_status_check
        check (status in ('started', 'stopped', 'failed', 'near_plot', 'visitor_confirmed')),
    constraint visitor_navigation_distance_check
        check (
            (planned_distance_meters is null or planned_distance_meters >= 0)
            and (estimated_distance_meters is null or estimated_distance_meters >= 0)
        ),
    constraint visitor_navigation_duration_check
        check (duration_seconds is null or duration_seconds >= 0),
    constraint visitor_navigation_time_order_check
        check (completed_at is null or completed_at >= started_at)
);

comment on table public.visitor_navigation is
    'Anonymous navigation attempts; planned route distance is separate from estimated distance walked.';

create index visitor_session_last_seen_idx
    on public.visitor_session (last_seen_at desc);

create index visitor_event_session_time_idx
    on public.visitor_event (session_id, event_timestamp desc);

create index visitor_event_name_time_idx
    on public.visitor_event (event_name, event_timestamp desc);

create index visitor_navigation_session_time_idx
    on public.visitor_navigation (session_id, started_at desc);

create index visitor_navigation_destination_area_idx
    on public.visitor_navigation (destination_area_code, started_at desc);

alter table public.visitor_session enable row level security;

alter table public.visitor_event enable row level security;

alter table public.visitor_navigation enable row level security;

revoke all on table public.visitor_session, public.visitor_event, public.visitor_navigation
from public, anon, authenticated;

revoke all on sequence public.visitor_event_event_id_seq, public.visitor_navigation_navigation_id_seq
from public, anon, authenticated;

create or replace function public.record_visitor_event(
    p_session_id uuid,
    p_device_type text,
    p_event_name text,
    p_properties jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    event_id_value bigint;
    normalized_device_type text := lower(coalesce(nullif(trim(p_device_type), ''), 'unknown'));
    normalized_properties jsonb := coalesce(p_properties, '{}'::jsonb);
begin
    if normalized_device_type not in ('desktop', 'mobile', 'tablet', 'unknown') then
        raise exception 'Invalid visitor device type';
    end if;

    if p_event_name not in (
        'page_viewed',
        'visitor_search_submitted',
        'public_record_opened',
        'map_opened',
        'garden_selected',
        'plot_selected',
        'navigation_started',
        'navigation_completed',
        'navigation_failed',
        'location_permission_denied',
        'gps_accuracy_low'
    ) then
        raise exception 'Invalid visitor event name';
    end if;

    if jsonb_typeof(normalized_properties) <> 'object'
       or pg_column_size(normalized_properties) > 4096 then
        raise exception 'Visitor event properties must be a small JSON object';
    end if;

    insert into public.visitor_session (session_id, device_type)
    values (p_session_id, normalized_device_type)
    on conflict (session_id) do update
       set last_seen_at = current_timestamp,
           device_type = case
               when public.visitor_session.device_type = 'unknown'
                    and excluded.device_type <> 'unknown'
               then excluded.device_type
               else public.visitor_session.device_type
           end;

    insert into public.visitor_event (session_id, event_name, properties)
    values (p_session_id, p_event_name, normalized_properties)
    returning event_id into event_id_value;

    return event_id_value;
end;
$$;

create or replace function public.record_visitor_navigation(
    p_session_id uuid,
    p_navigation_id bigint default null,
    p_device_type text default 'unknown',
    p_status text default 'started',
    p_planned_distance_meters numeric default null,
    p_estimated_distance_meters numeric default null,
    p_duration_seconds integer default null,
    p_error_type text default null,
    p_destination_area_code text default null
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    navigation_id_value bigint;
    normalized_device_type text := lower(coalesce(nullif(trim(p_device_type), ''), 'unknown'));
    normalized_status text := lower(coalesce(nullif(trim(p_status), ''), 'started'));
begin
    if normalized_device_type not in ('desktop', 'mobile', 'tablet', 'unknown') then
        raise exception 'Invalid visitor device type';
    end if;

    if normalized_status not in ('started', 'stopped', 'failed', 'near_plot', 'visitor_confirmed') then
        raise exception 'Invalid visitor navigation status';
    end if;

    if p_planned_distance_meters is not null and p_planned_distance_meters < 0 then
        raise exception 'Planned distance cannot be negative';
    end if;

    if p_estimated_distance_meters is not null and p_estimated_distance_meters < 0 then
        raise exception 'Estimated distance cannot be negative';
    end if;

    if p_duration_seconds is not null and p_duration_seconds < 0 then
        raise exception 'Duration cannot be negative';
    end if;

    if p_destination_area_code is not null and char_length(trim(p_destination_area_code)) > 100 then
        raise exception 'Destination area code is too long';
    end if;

    insert into public.visitor_session (session_id, device_type)
    values (p_session_id, normalized_device_type)
    on conflict (session_id) do update
       set last_seen_at = current_timestamp,
           device_type = case
               when public.visitor_session.device_type = 'unknown'
                    and excluded.device_type <> 'unknown'
               then excluded.device_type
               else public.visitor_session.device_type
           end;

    if p_navigation_id is null then
        insert into public.visitor_navigation (
            session_id,
            planned_distance_meters,
            estimated_distance_meters,
            duration_seconds,
            status,
            error_type,
            destination_area_code
        ) values (
            p_session_id,
            p_planned_distance_meters,
            p_estimated_distance_meters,
            p_duration_seconds,
            normalized_status,
            nullif(trim(p_error_type), ''),
            nullif(trim(p_destination_area_code), '')
        ) returning navigation_id into navigation_id_value;
    else
        update public.visitor_navigation
           set completed_at = case
                   when normalized_status in ('stopped', 'failed', 'near_plot', 'visitor_confirmed')
                   then current_timestamp
                   else completed_at
               end,
               planned_distance_meters = coalesce(p_planned_distance_meters, planned_distance_meters),
               estimated_distance_meters = coalesce(p_estimated_distance_meters, estimated_distance_meters),
               duration_seconds = coalesce(p_duration_seconds, duration_seconds),
               status = normalized_status,
               error_type = coalesce(nullif(trim(p_error_type), ''), error_type),
               destination_area_code = coalesce(nullif(trim(p_destination_area_code), ''), destination_area_code)
         where navigation_id = p_navigation_id
           and session_id = p_session_id
        returning navigation_id into navigation_id_value;

        if navigation_id_value is null then
            raise exception 'Navigation attempt was not found for this session';
        end if;
    end if;

    return navigation_id_value;
end;
$$;

revoke all on function public.record_visitor_event(uuid, text, text, jsonb) from public;

revoke all on function public.record_visitor_navigation(uuid, bigint, text, text, numeric, numeric, integer, text, text) from public;

grant execute on function public.record_visitor_event(uuid, text, text, jsonb) to anon, authenticated;

grant execute on function public.record_visitor_navigation(uuid, bigint, text, text, numeric, numeric, integer, text, text) to anon, authenticated;
